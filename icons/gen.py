# Grid 24x24, garis 2, ujung & sambungan membulat. Operasi:
#  L x1 y1 x2 y2 | C cx cy r (lingkaran garis) | D cx cy r (lingkaran isi) | P poligon isi | S polyline garis
#  Z poligon tertutup garis | R x y w h r (kotak membulat garis) | F x y w h r (kotak membulat isi) | A cx cy r a0 sweep (busur)
import math, json, sys

def bez(p0, p1, p2, p3, n=14):
    pts = []
    for i in range(1, n + 1):
        t = i / n; u = 1 - t
        x = u**3*p0[0] + 3*u*u*t*p1[0] + 3*u*t*t*p2[0] + t**3*p3[0]
        y = u**3*p0[1] + 3*u*u*t*p1[1] + 3*u*t*t*p2[1] + t**3*p3[1]
        pts += [round(x, 2), round(y, 2)]
    return pts

def ray(cx, cy, r0, r1, deg):
    a = math.radians(deg)
    return ("L", round(cx + r0*math.cos(a), 2), round(cy + r0*math.sin(a), 2), round(cx + r1*math.cos(a), 2), round(cy + r1*math.sin(a), 2))

