def fmt(op):
    c = op[0]; rest = []
    for v in op[1:]:
        if isinstance(v, list): rest += v
        else: rest.append(v)
    return c + ",".join(("%g" % x) for x in rest)

def kotlin():
    out = ["package com.alya.gamespace", "", "// DIHASILKAN OTOMATIS oleh icons/gen.py. Jangan diedit manual.", "object Ic {"]
    for i, n in enumerate(names):
        out.append("    const val %s = %d" % (n.upper(), i))
    out.append("")
    out.append("    val NAMES = arrayOf(" + ", ".join('"%s"' % n for n in names) + ")")
    out.append("    /** Setiap ikon: operasi dipisah '|' (L garis · C/D lingkaran · P/Z/S poligon · R/F kotak · A busur). */")
    out.append("    val SRC = arrayOf(")
    for n in names:
        out.append('        "' + "|".join(fmt(o) for o in I[n]) + '",')
    out.append("    )")
    out.append("}")
    return "\n".join(out) + "\n"

